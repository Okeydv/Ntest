-- Когда участник вошёл в комнату: нужно для разметки истории («вошёл
-- позже — этого не видел») и для запросов на вход. У старых записей времени
-- нет — его никто не записывал, и выдумывать его нельзя: они остаются NULL.
-- Поэтому колонка добавляется без значения по умолчанию, а default ставится
-- отдельно; иначе все старые участники «вошли» бы в момент миграции (та же
-- ошибка, что была с created_at у сообщений, см. 002).
ALTER TABLE room_participants ADD COLUMN IF NOT EXISTS joined_at TIMESTAMPTZ;
ALTER TABLE room_participants ALTER COLUMN joined_at SET DEFAULT now();
