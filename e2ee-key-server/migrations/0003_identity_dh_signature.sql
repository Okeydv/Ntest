-- Подпись X25519-ключа личности Ed25519-ключом того же устройства
-- (crypto::verify_identity_dh). Без неё ключ для DH ничем не был связан
-- с ключом подписи: сервер мог отдать чужой DH-ключ при настоящем ключе
-- подписи. У устройств, зарегистрированных раньше, подписи нет, пока они
-- не запустятся снова и не допишут её.
ALTER TABLE identity_keys ADD COLUMN IF NOT EXISTS identity_dh_signature BYTEA;
